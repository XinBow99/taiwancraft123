    private final float chassisY;

    public LanbaoModel(ModelPart root) {
        // 理由同機車：預設的 cutout-no-cull 會讓車殼內外側一起畫、互相穿插，
        // 看起來像整台車是半透明的
        super(root, RenderTypes::entitySolid);
        this.chassis = root.getChild("chassis");
        this.wheelFl = root.getChild("wheel_fl");
        this.wheelFr = root.getChild("wheel_fr");
        this.wheelRl = root.getChild("wheel_rl");
        this.wheelRr = root.getChild("wheel_rr");
        this.chassisY = this.chassis.y;
    }

    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();

        root.addOrReplaceChild("chassis",
                chassis0(chassis1(chassis2(chassis3(CubeListBuilder.create())))),
                PartPose.offset(0.0000f, 18.6540f, 20.2500f));

        root.addOrReplaceChild("wheel_fl",
                wheelFl0(CubeListBuilder.create()),
                PartPose.offset(-12.9600f, 18.6540f, -21.0600f));

        root.addOrReplaceChild("wheel_fr",
                wheelFr0(CubeListBuilder.create()),
                PartPose.offset(12.9600f, 18.6540f, -21.0600f));

        root.addOrReplaceChild("wheel_rl",
                wheelRl0(CubeListBuilder.create()),
                PartPose.offset(-12.9600f, 18.6540f, 20.2500f));

        root.addOrReplaceChild("wheel_rr",
                wheelRr0(CubeListBuilder.create()),
                PartPose.offset(12.9600f, 18.6540f, 20.2500f));

        return LayerDefinition.create(mesh, 256, 256);
    }

