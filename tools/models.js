// ---------------------------------------------------------------- 體素風的產生器
//
// 軸對齊的大方塊做不出斜線。體素模型的曲線是「一片一片方的橫斷面，堆起來才有斜線」——
// 所以下面兩支把折線與輪廓展開成一串小方塊。手寫一百多個零件不可行，而且改一次線條
// 就要全部重排；用產生的，改的是折線上的幾個點。

/**
 * 整台等比放大。**以地面（y=24）為基準**——放大之後輪子還是要站在地上，
 * 直接把 y 乘上去的話整台會陷進地裡。
 *
 * 子件的 pose 是相對父件的，所以只有頂層零件要做地面錨定；子件單純等比。
 */
function scaleParts(parts, k) {
  const groundY = (y) => 24 - (24 - y) * k;
  return parts.map(([name, parent, origin, size, pose, rot, colour]) => [
    name, parent,
    origin.map((v) => v * k),
    size.map((v) => v * k),
    parent ? pose.map((v) => v * k) : [pose[0] * k, groundY(pose[1]), pose[2] * k],
    rot, colour,
  ]);
}

/**
 * 沿著折線堆一串小方塊（車殼上那道紅色的鉤就是這樣來的）。
 * pts 是 [z, y] 的序列（模型座標，y 往下為正），每段切成 step 長的小塊。
 */
function ridge(prefix, pts, opt) {
  const { x = 0, w = 1, t = 1, colour, step = 1, depth = null } = opt;
  const out = [];
  let n = 0;
  for (let i = 0; i < pts.length - 1; i++) {
    const [z0, y0] = pts[i];
    const [z1, y1] = pts[i + 1];
    const count = Math.max(1, Math.round(Math.hypot(z1 - z0, y1 - y0) / step));
    for (let k = 0; k < count; k++) {
      const f = (k + 0.5) / count;
      const d = depth ?? step * 1.15;   // 稍微重疊，不然階梯之間會透光
      out.push([
        prefix + (n++), null,
        [-w / 2, -t / 2, -d / 2], [w, t, d],
        [x, y0 + (y1 - y0) * f, z0 + (z1 - z0) * f], [0, 0, 0], colour,
      ]);
    }
  }
  return out;
}

/**
 * 把側面輪廓切成一片片橫斷面。每筆是 [z, yTop, yBottom, width, colour]。
 * 每一片自己是方的，靠彼此的高低差堆出曲面。
 */
function slabs(prefix, list, depth = 1.1) {
  return list.map(([z, yTop, yBot, w, colour], i) => [
    prefix + i, null,
    [-w / 2, 0, -depth / 2], [w, yBot - yTop, depth],
    [0, yTop, z], [0, 0, 0], colour,
  ]);
}

